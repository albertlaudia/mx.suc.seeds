window.computeShippingFee = function(items) {
  const lineItems = items.map(i => {
    const product = window.PRODUCTS.find(p => p.id === i.id);
    const weightGrams = (product ? product.weightGrams : 100) * i.qty;
    const billableUnits = Math.max(1, Math.ceil(weightGrams / 100));
    const shippingSgd = billableUnits * window.SHIPPING.ratePer100gSgd;
    return {
      id: i.id,
      qty: i.qty,
      weightGrams,
      billableUnits,
      shippingSgd
    };
  });
  const totalGrams = lineItems.reduce((s, l) => s + l.weightGrams, 0);
  const shippingTotalSgd = lineItems.reduce((s, l) => s + l.shippingSgd, 0);
  const subtotalSgd = items.reduce((s, i) => {
    const p = window.PRODUCTS.find(x => x.id === i.id);
    return s + (p ? p.priceSgd * i.qty : 0);
  }, 0);
  const markupPct = window.SHIPPING.markupPct;
  const markupSgd = (subtotalSgd + shippingTotalSgd) * markupPct / 100;
  const totalSgd = subtotalSgd + shippingTotalSgd + markupSgd;
  return {
    lineItems,
    totalGrams,
    shippingSgd: shippingTotalSgd,
    subtotalSgd,
    markupPct,
    markupSgd,
    totalSgd
  };
};

